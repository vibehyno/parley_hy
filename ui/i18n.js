  function browserLocale() {
    return String(global.navigator?.language || "en").toLowerCase().startsWith("ko") ? "ko" : "en";
  }
  function savedLocale() {
    try {
      const saved = global.localStorage?.getItem(STORAGE_KEY);
      return saved === "ko" || saved === "en" ? saved : null;
    } catch { return null; }
  }
  let locale = savedLocale() || browserLocale();
  function currentLocale() { return locale; }
  function toolDescription(name, original = "") {
    const source = String(original || "");
    if (locale !== "ko") return source;
    return SKILL_DESCRIPTIONS_KO[String(name || "").toLowerCase()] || source;
  }
  function t(key, vars = {}) {
    let value = DICT[locale]?.[key] ?? DICT.en[key] ?? key;
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
    return value;
  }
  function applyLocale(root = global.document) {
    if (!root) return;
    if (global.document?.documentElement) global.document.documentElement.lang = locale;
    for (const el of root.querySelectorAll?.("[data-i18n]") || []) el.textContent = t(el.dataset.i18n);
    for (const el of root.querySelectorAll?.("[data-i18n-placeholder]") || []) {
      el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
    }
    for (const el of root.querySelectorAll?.("[data-i18n-title]") || []) {
      el.setAttribute("title", t(el.dataset.i18nTitle));
    }
    for (const el of root.querySelectorAll?.("[data-i18n-aria-label]") || []) {
      el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
    }
  }
  function setLocale(next) {
    locale = next === "ko" ? "ko" : "en";
    try { global.localStorage?.setItem(STORAGE_KEY, locale); } catch { /* unavailable storage */ }
    applyLocale();
    return locale;
  }

  global.ParleyI18n = { STORAGE_KEY, currentLocale, t, toolDescription, setLocale, applyLocale };
